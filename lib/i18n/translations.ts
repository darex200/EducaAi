export type TranslationKey = keyof typeof translations.en;

export function t(locale: AppLocale, key: TranslationKey, vars?: Record<string, string>) {
  let text: string = translations[locale][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, value);
    }
  }
  return text;
}

export function difficultyLabel(
  locale: AppLocale,
  difficulty: "basico" | "intermedio" | "avanzado" | string,
) {
  const map = {
    basico: "difficultyBasic",
    intermedio: "difficultyIntermediate",
    avanzado: "difficultyAdvanced",
  } as const;
  const key = map[difficulty as keyof typeof map];
  return key ? t(locale, key) : difficulty;
}

export function academicLevelLabel(locale: AppLocale, level: string) {
  const map = {
    primaria: "levelPrimary",
    secundaria: "levelSecondary",
    bachillerato: "levelHighSchool",
    universidad: "levelUniversity",
  } as const;
  const key = map[level as keyof typeof map];
  return key ? t(locale, key) : level;
}

export function localeInstruction(locale: AppLocale) {
  if (locale === "es") {
    return "IMPORTANTE: Responde SIEMPRE en español. Todos los mensajes del tutor deben estar en español.";
  }
  if (locale === "pt") {
    return "IMPORTANTE: Responda SEMPRE em português. Todas as mensagens do tutor devem estar em português.";
  }
  return "IMPORTANT: Always respond in English. Every tutor message must be in English.";
}

export function dateLocaleTag(locale: AppLocale) {
  if (locale === "es") return "es-ES";
  if (locale === "pt") return "pt-BR";
  return "en-US";
}
